using Mscc.GenerativeAI;
using TraderView.Application.Interfaces.Services;
using TraderView.Application.Interfaces.Services.AI;
using TraderView.Domain.Entities;

namespace TraderView.Application.Services.AI
{      
    public class GoogleAIStudioService : IGoogleAIStudioService
    {
        private readonly IAIReportService _aiReportService;
        private readonly IAIReportInstructionService _aiReportInstructionService;
        private readonly string _apiKey;
        private readonly string _model;

        public GoogleAIStudioService(IAIReportService aiReportService, IAIReportInstructionService aiReportInstructionService, string apiKey, string model)
        {
            _aiReportService = aiReportService;
            _aiReportInstructionService = aiReportInstructionService;
            _apiKey = apiKey;
            _model = model;
        }
        async Task<string> IGoogleAIStudioService.GenerateReportAsync(int instructionId, IReadOnlyList<Position> openPositions)
        {
            try
            {
                var instruction = await _aiReportInstructionService.GetByIdAsync(instructionId);
                if (instruction == null)
                {
                    throw new ArgumentException($"No instruction found with ID {instructionId}");
                }
                var prompt = GeneratePromptWithPositions(instruction, openPositions, instruction.Instruction);
                var googleAI = new GoogleAI(_apiKey);
                var model = googleAI.GenerativeModel(model: _model);
                var response = await model.GenerateContent(prompt);
                if (response is not null)
                {
                    await _aiReportService.CreateAsync(instructionId, response.Text);
                    return response.Text;
                }
                return "No response generated by the model.";
            }
            catch(Exception ex)
            {
                // Log the exception (you can use any logging framework you prefer)
                Console.WriteLine($"Error generating report: {ex.Message}");
                throw; // Re-throw the exception after logging it
            }
        }
        private string GeneratePromptWithPositions(AIReportInstruction instruction1, IReadOnlyList<Position> positions, string instruction2)
        {
            var positionString = "NO OPEN POSITIONS";
            if (positions.Any())
            {
                positionString = string.Join("; ", positions.Select(p => $"{p.Instrument.ListingExchange}:{p.Instrument.DataName}"));
            }
            return instruction1.Instruction.Replace("[INSERT_POSITION_LIST]", positionString);
        }
    }
}
