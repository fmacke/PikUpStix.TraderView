using Mscc.GenerativeAI;
using Mscc.GenerativeAI.Types;
using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Text.Json;
using System.Threading.Tasks;
using TraderView.Application.Interfaces.Services;
using TraderView.Application.Interfaces.Services.AI;
using TraderView.Domain.Entities;

namespace TraderView.Application.Services.AI
{
    public class GoogleAIStudioService : IGoogleAIStudioService
    {
        private readonly IAIReportService _aiReportService;
        private readonly IAIReportInstructionService _aiReportInstructionService;
        private readonly IMarketDataService _fmpService;
        private readonly string _apiKey;
        private readonly string _model;

        public GoogleAIStudioService(
            IAIReportService aiReportService,
            IAIReportInstructionService aiReportInstructionService,
            IMarketDataService fmpService,
            string apiKey,
            string model)
        {
            _aiReportService = aiReportService;
            _aiReportInstructionService = aiReportInstructionService;
            _fmpService = fmpService;
            _apiKey = apiKey;
            _model = model;
        }

        public async Task<string> GenerateReportAsync(int instructionId, IReadOnlyList<Position> openPositions)
        {
            try
            {
                var instruction = await _aiReportInstructionService.GetByIdAsync(instructionId);
                if (instruction == null)
                {
                    throw new ArgumentException($"No instruction found with ID {instructionId}");
                }

                var googleAI = new GoogleAI(_apiKey);

                // System instructions anchor the CAN SLIM / SEPA persona
                var systemInstruction = new Content(
                    "You are an expert quantitative macro and equity trading assistant specializing in " +
                    "position and swing trading using William O'Neil's CAN SLIM rules and Mark Minervini's SEPA strategy. Always query market data " +
                    "and news using available functions to verify price action, market direction, and catalysts before advising."
                );

                var model = googleAI.GenerativeModel(
                    model: _model,
                    systemInstruction: systemInstruction,
                    tools: GetMarketDataTools()
                );

                // Initialize chat session so the model remembers function call iterations
                var chat = model.StartChat();
                var userPrompt = BuildUserPrompt(instruction.Instruction, openPositions);

                var response = await chat.SendMessage(userPrompt);

                // Function Execution Loop: execute tools while Gemini requests function calls
                while (response.FunctionCalls != null && response.FunctionCalls.Any())
                {
                    var functionCall = response.FunctionCalls.First();
                    var toolResultJson = await ExecuteToolAsync(functionCall);

                    // Build a proper FunctionResponse object wrapped in a List<Part> or dictionary format 
                    // expected by the strong-typed Mscc.GenerativeAI overloads.
                    var functionResponsePart = new Part
                    {
                        FunctionResponse = new FunctionResponse
                        {
                            Name = functionCall.Name,
                            Response = new Dictionary<string, object>
                            {
                                { "result", toolResultJson }
                            }
                        }
                    };

                    // Send the function execution output back to the model via the active chat session
                    response = await chat.SendMessage(new List<Part> { functionResponsePart });
                }

                if (!string.IsNullOrWhiteSpace(response.Text))
                {
                    await _aiReportService.CreateAsync(instructionId, response.Text);
                    return response.Text;
                }

                return "No response generated by the model.";
            }
            catch (Exception ex)
            {
                Console.WriteLine($"Error generating report in GoogleAIStudioService: {ex.Message}");
                throw;
            }
        }

        private Tools GetMarketDataTools()
        {
            Tools k = new Tools()
            {
                new Tool
                {
                    FunctionDeclarations = new List<FunctionDeclaration>
                    {
                        new FunctionDeclaration
                        {
                            Name = "GetStockQuotes",
                            Description = "Fetch latest real-time prices, percentage changes, and daily highs/lows for market indices or stock tickers.",
                            Parameters = new Schema
                            {
                                Type = ParameterType.Object,
                                Properties = new Dictionary<string, Schema>
                                {
                                    { "tickers", new Schema { Type = ParameterType.String, Description = "Comma-separated list of symbols" } }
                                },
                                Required = new List<string> { "tickers" }
                            }
                        },
                        new FunctionDeclaration
                        {
                            Name = "GetStockNews",
                            Description = "Fetch top news stories and market headlines for macro indices or portfolio tickers.",
                            Parameters = new Schema
                            {
                                Type = ParameterType.Object,
                                Properties = new Dictionary<string, Schema>
                                {
                                    { "tickers", new Schema { Type = ParameterType.String, Description = "Comma-separated list of tickers" } },
                                    { "limit", new Schema { Type = ParameterType.Integer, Description = "Number of news articles to retrieve" } }
                                },
                                Required = new List<string> { "tickers" }
                            }
                        },
                        new FunctionDeclaration
                        {
                            Name = "GetEconomicCalendar",
                            Description = "Fetch major economic event releases (CPI, PPI, FOMC, NFP, Unemployment) for the current day.",
                            Parameters = new Schema
                            {
                                Type = ParameterType.Object,
                                Properties = new Dictionary<string, Schema>()
                            }
                        },
                        new FunctionDeclaration
                        {
                            Name = "GetGeneralMarketNews",
                            Description = "Fetch general market news and headlines.",
                            Parameters = new Schema
                            {
                                Type = ParameterType.Object,
                                Properties = new Dictionary<string, Schema>
                                {
                                    { "to", new Schema { Type = ParameterType.String, Description = "To date" } },
                                    { "from", new Schema { Type = ParameterType.String, Description = "From date" } },
                                    { "limit", new Schema { Type = ParameterType.Integer, Description = "Number of news articles to retrieve" } }
                                }
                            }
                        }
                    }
                }
            };
            return k;
        }

        private async Task<string> ExecuteToolAsync(FunctionCall functionCall)
        {
            switch (functionCall.Name)
            {
                case "GetStockQuotes":
                    var args = JsonSerializer.Deserialize<Dictionary<string, object>>(functionCall.Args.ToString());
                    var tickers = args?["tickers"]?.ToString();
                    return await _fmpService.GetMarketQuotesAsync(tickers);
                case "GetGeneralMarketNews":
                    return await _fmpService.GetGeneralMarketNewsAsync(DateTime.Now.AddDays(-1), DateTime.Now, 25);
                case "GetStockNews":
                    var newsArgs = JsonSerializer.Deserialize<Dictionary<string, object>>(functionCall.Args.ToString());
                    var newsTickers = newsArgs?["tickers"]?.ToString();
                    int limit = 5;
                    if (newsArgs?.ContainsKey("limit") == true)
                    {
                        var limitObj = newsArgs["limit"];
                        int.TryParse(limitObj?.ToString(), out limit);
                    }
                    return await _fmpService.GetStockNewsAsync(newsTickers, limit);

                case "GetEconomicCalendar":
                    return await _fmpService.GetEconomicCalendarAsync();

                default:
                    throw new NotImplementedException($"Tool function {functionCall.Name} is not implemented.");
            }
        }

        private string BuildUserPrompt(string baseInstruction, IReadOnlyList<Position> positions)
        {
            var positionSb = new StringBuilder();
            if (positions != null && positions.Any())
            {
                foreach (var p in positions)
                {
                    positionSb.AppendLine($"- Ticker: {p.Instrument.ListingExchange}:{p.Instrument.DataName} | Status: {p.Status}");
                }
            }
            else
            {
                positionSb.AppendLine("NO OPEN POSITIONS (100% Cash Exposure)");
            }

            return $"""
            {baseInstruction}

            ### CURRENT OPEN POSITIONS (TraderView DB):
            {positionSb}

            ### EXECUTION INSTRUCTIONS:
            1. Use available function calls to fetch market news for market benchmarks nd general news, stock quotation details, stock news and details about up and coming economic events
            2. Fetch the economic calendar for today's risk events.
            3. Evaluate market direction under CAN SLIM criteria (Market in Confirmed Uptrend, Uptrend Under Pressure, or Market in Correction).
            4. Highlight key catalysts, earnings dates, or stop-loss adjustments for open positions.
            """;
        }
    }
}